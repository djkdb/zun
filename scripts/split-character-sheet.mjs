#!/usr/bin/env node
/**
 * Split the official ZUN character sheet into 32 pose PNGs.
 *
 *   node scripts/split-character-sheet.mjs [public/character/zun-sheet.png]
 *
 * Expects an 8 × 4 grid (poses 01–32, row-major). For every cell it:
 *   1. erases the "01".."32" label in the top-left corner,
 *   2. turns a baked-in checkerboard background transparent (if present),
 *   3. trims transparent margins,
 *   4. writes public/character/poses/NN.png
 * and finally regenerates data/character-manifest.ts so the site switches
 * from the code-drawn SVG fallback to the real sprites.
 */
import sharp from "sharp";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const COLS = 8, ROWS = 4;
const src = resolve(process.argv[2] ?? "public/character/zun-sheet.png");
const outDir = resolve("public/character/poses");
if (!existsSync(src)) {
  console.error(`Sheet not found: ${src}\nPut the sheet at public/character/zun-sheet.png and re-run.`);
  process.exit(1);
}
mkdirSync(outDir, { recursive: true });

const img = sharp(src).ensureAlpha();
const { width, height } = await img.metadata();
const cw = Math.floor(width / COLS), ch = Math.floor(height / ROWS);
const { data } = await img.raw().toBuffer({ resolveWithObject: true });
console.log(`sheet ${width}×${height} → cells ${cw}×${ch}`);

// --- checkerboard detection: sample the four corners of the sheet -----------
const px = (x, y) => { const i = (y * width + x) * 4; return [data[i], data[i + 1], data[i + 2], data[i + 3]]; };
const corners = [px(2, 2), px(width - 3, 2), px(2, height - 3), px(width - 3, height - 3)];
const baked = corners.every(([r, g, b, a]) => a > 250 && r > 180 && g > 180 && b > 180 && Math.abs(r - g) < 12 && Math.abs(g - b) < 12);
const isChecker = ([r, g, b, a]) => a > 250 && r > 185 && g > 185 && b > 185 && Math.abs(r - g) < 14 && Math.abs(g - b) < 14 && Math.abs(r - b) < 14;
console.log(baked ? "baked checkerboard detected → removing via edge flood fill" : "transparent background detected");

const manifest = {};
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    const n = row * COLS + col + 1;
    const id = String(n).padStart(2, "0");
    const x0 = col * cw, y0 = row * ch;
    const cell = Buffer.alloc(cw * ch * 4);
    for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) {
      const si = ((y0 + y) * width + (x0 + x)) * 4, di = (y * cw + x) * 4;
      cell[di] = data[si]; cell[di + 1] = data[si + 1]; cell[di + 2] = data[si + 2]; cell[di + 3] = data[si + 3];
    }
    // 1) label eraser: everything within the top-left label box becomes transparent
    const LW = Math.round(cw * 0.32), LH = Math.round(ch * 0.2);
    for (let y = 0; y < LH; y++) for (let x = 0; x < LW; x++) cell[(y * cw + x) * 4 + 3] = 0;
    // 2) checkerboard removal: flood fill from the cell edges over checker-coloured pixels only,
    //    so whites inside the character (eyes, sneakers) survive.
    if (baked) {
      const seen = new Uint8Array(cw * ch);
      const stack = [];
      for (let x = 0; x < cw; x++) { stack.push(x, 0, x, ch - 1); }
      for (let y = 0; y < ch; y++) { stack.push(0, y, cw - 1, y); }
      while (stack.length) {
        const y = stack.pop(), x = stack.pop();
        if (x < 0 || y < 0 || x >= cw || y >= ch) continue;
        const k = y * cw + x;
        if (seen[k]) continue;
        seen[k] = 1;
        const i = k * 4;
        const p = [cell[i], cell[i + 1], cell[i + 2], cell[i + 3]];
        if (!(isChecker(p) || p[3] === 0)) continue;
        cell[i + 3] = 0;
        stack.push(x + 1, y, x - 1, y, x, y + 1, x, y - 1);
      }
    }
    const out = await sharp(cell, { raw: { width: cw, height: ch, channels: 4 } }).trim({ threshold: 1 }).png().toBuffer();
    const meta = await sharp(out).metadata();
    writeFileSync(resolve(outDir, `${id}.png`), out);
    manifest[id] = { w: meta.width, h: meta.height };
    process.stdout.write(`${id} ${meta.width}×${meta.height}  `);
  }
  process.stdout.write("\n");
}

const ts = `/**
 * GENERATED by scripts/split-character-sheet.mjs — do not edit by hand.
 * available=true switches ZunCharacter from the SVG fallback to /character/poses/NN.png
 */
export const characterManifest = {
  available: true,
  cells: ${JSON.stringify(manifest, null, 2).replace(/"(\d+)":/g, '"$1":')} as Record<string, { w: number; h: number }>,
} as const;
`;
writeFileSync(resolve("data/character-manifest.ts"), ts);
console.log("\nwrote data/character-manifest.ts (available: true)");
